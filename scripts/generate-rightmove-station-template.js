/*
 * Dev helper: generate a TypeScript template listing all London Tube stations
 * with stationId + suggested searchLocation, and empty Rightmove fields
 * ready for you to fill in locationIdentifier/displayLocationIdentifier.
 *
 * Usage (from repo root):
 *   node scripts/generate-rightmove-station-template.js
 *
 * Output:
 *   docs/rightmove-station-template.ts
 */
/* eslint-disable @typescript-eslint/no-require-imports */

const fs = require('fs')
const path = require('path')

const rootDir = path.join(__dirname, '..')
const stationsPath = path.join(rootDir, 'public', 'data', 'stations.json')
const outputPath = path.join(rootDir, 'docs', 'rightmove-station-template.ts')

/**
 * Clean a TfL displayName into a Rightmove-style searchLocation.
 * Example: "Mansion House Underground Station" -> "Mansion House Station".
 */
function toSearchLocation(displayName) {
  if (!displayName || typeof displayName !== 'string') return ''
  return displayName.replace(/ Underground Station$/i, ' Station').trim()
}

function main() {
  const raw = fs.readFileSync(stationsPath, 'utf8')
  const parsed = JSON.parse(raw)
  const stations = Array.isArray(parsed) ? parsed : parsed.stations

  if (!Array.isArray(stations)) {
    throw new Error('Unexpected stations.json shape: expected an array or { stations: [...] }')
  }

  const headerLines = [
    '// Auto-generated by scripts/generate-rightmove-station-template.js',
    '// Do not edit this file by hand; instead, re-run the script or copy entries you need.',
    '',
    'export interface RightmoveStationTemplateEntry {',
    "  stationId: string",
    "  searchLocation: string",
    "  locationIdentifier: string",
    "  displayLocationIdentifier: string",
    "  displayName?: string",
    "  matchStatus?: 'matched' | 'unmatched' | 'ambiguous'",
    "  lastVerifiedAt?: string",
    '}',
    '',
    'export const RIGHTMOVE_STATION_TEMPLATE: RightmoveStationTemplateEntry[] = [',
  ]

  const bodyLines = stations.map((station) => {
    const stationId = station.stationId
    const displayName = station.displayName
    const rawSearchLocation = toSearchLocation(displayName)
    const searchLocation = rawSearchLocation.replace(/'/g, "\\'")
    const baseDisplayLocationIdentifier = rawSearchLocation.replace(/\s+/g, '-')
    const withStationSuffix = baseDisplayLocationIdentifier.endsWith('-Station')
      ? baseDisplayLocationIdentifier
      : `${baseDisplayLocationIdentifier}-Station`
    const displayLocationIdentifier = withStationSuffix.replace(/'/g, "\\'")

    return `  { stationId: '${stationId}', searchLocation: '${searchLocation}', locationIdentifier: '', displayLocationIdentifier: '${displayLocationIdentifier}', matchStatus: 'unmatched' },`
  })

  const footerLines = [
    ']',
    '',
  ]

  const content = headerLines.concat(bodyLines, footerLines).join('\n')
  fs.writeFileSync(outputPath, content, 'utf8')

  console.log(`Rightmove station template written to ${outputPath}`)
}

if (require.main === module) {
  main()
}
